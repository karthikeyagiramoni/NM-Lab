import numpy as np

n=15
x=np.zeros(n)
a=np.array([0,-1.0,-1.1,-1.3,-1.0,-1.2,-1.5,-1.1,-1.0,-1.4,-1.2,-1.0,-1.3,-1.1,-1.2])
b=np.array([4.5,4.8,5.0,4.6,5.2,4.9,5.5,4.7,5.0,4.8,5.1,4.6,5.3,4.9,4.5])
c=np.array([-1.2,-1.5,-1.2,-1.0,-1.4,-1.1,-1.3,-1.2,-1.5,-1.1,-1.3,-1.2,-1.0,-1.4,0])
d=np.array([10.5,12.0,-8.5,15.2,6.8,-4.0,22.1,11.5,-9.3,14.0,7.4,-2.5,18.6,5.0,13.2])

a1=np.array([0,-1.0,-1.1,-1.3,-1.0,-1.2,-1.5,-1.1,-1.0,-1.4,-1.2,-1.0,-1.3,-1.1,-1.2])
b1=np.array([4.5,4.8,5.0,4.6,5.2,4.9,5.5,4.7,5.0,4.8,5.1,4.6,5.3,4.9,4.5])
c1=np.array([-1.2,-1.5,-1.2,-1.0,-1.4,-1.1,-1.3,-1.2,-1.5,-1.1,-1.3,-1.2,-1.0,-1.4,0])
d1=np.array([10.5,12.0,-8.5,15.2,6.8,-4.0,22.1,11.5,-9.3,14.0,7.4,-2.5,18.6,5.0,13.2])

for i in range(1,n):
    w=a[i]/b[i-1]
    b[i]=b[i]-w*c[i-1]
    d[i]=d[i]-w*d[i-1]

x[n-1]=d[n-1]/b[n-1]
for i in range(n-2,-1,-1):
    x[i]=(d[i]-c[i]*x[i+1])/b[i]

print("\nSolution:")
print(np.round(x,6))
rhs=np.zeros(n)

rhs[0]=d1[0]-(b1[0]*x[0]+c1[0]*x[1])
for i in range(1,n-1):
        rhs[i]=d1[i]-(a1[i]*x[i-1]+b1[i]*x[i]+c1[i]*x[i+1])
rhs[n-1]=d1[n-1]-(a1[n-1]*x[n-2]+b1[n-1]*x[n-1])
print("\nResidual Vector:")
print(rhs)

print("\nResidual inf-norm:")
print(np.max(np.abs(rhs)))